for (const [
  name,
  layer,
  port,
  transport,
  full,
  about,
  exchange,
  localEndpoint,
] of extraLessons) {
  colors[name] = securityLessons.has(name)
    ? 'var(--signal-mauve)'
    : layer <= 4
      ? 'var(--signal-green)'
      : 'var(--signal-slate)';
  protocols.push({
    name,
    full,
    layer,
    port,
    transport,
    about,
    tip:
      layer <= 2
        ? 'This exchange happens within a local link.'
        : 'Some related messages are shown together.',
    localEndpoint,
    steps: exchange.map(([label, detail, reply, upstream]) => {
      return [
        label,
        upstream ? (reply ? 2 : 1) : reply ? (name === 'Reverse proxy' ? 1 : 2) : 0,
        upstream ? (reply ? 1 : 2) : reply ? 0 : name === 'Reverse proxy' ? 1 : 2,
        name,
        detail,
      ];
    }),
  });
}
